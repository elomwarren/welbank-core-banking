--changeset elomwarren:0006-loan-classes-bands-as
--comment: Classification bands never overlap: a number of days past due belongs to one class only.
CREATE ASSERTION loan_classes_bands_as CHECK (
  NOT EXISTS (SELECT 1 FROM loan_classes a, loan_classes b
               WHERE a.class_code <> b.class_code
                 AND a.min_days_past_due <= b.max_days_past_due
                 AND b.min_days_past_due <= a.max_days_past_due));
--rollback DROP ASSERTION loan_classes_bands_as;

--changeset elomwarren:0006-loans-classification-as
--comment: A loan is never classified better than its days past due allow (worse is allowed: judgement).
-- Works both ways: changing a band refuses until the loans it affects are reclassified.
CREATE ASSERTION loans_classification_as CHECK (
  NOT EXISTS (SELECT 1 FROM loans l, loan_classes c
               WHERE c.class_code = l.classification AND l.days_past_due > c.max_days_past_due));
--rollback DROP ASSERTION loans_classification_as;

--changeset elomwarren:0006-loans-accounts-as
