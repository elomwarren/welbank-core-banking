CREATE TABLE loan_schedule (
  loan_id         NUMBER(10)           NOT NULL,
  installment_no  NUMBER(3)            NOT NULL,
  due_date        DATE                 NOT NULL,
  principal_due   non_negative_money_d NOT NULL,
  interest_due    non_negative_money_d NOT NULL,
  total_due       NUMBER(15, 2)        GENERATED ALWAYS AS (principal_due + interest_due) VIRTUAL,
  principal_paid  non_negative_money_d DEFAULT ON NULL 0,
  interest_paid   non_negative_money_d DEFAULT ON NULL 0,
  status          VARCHAR2(8)          DEFAULT ON NULL 'DUE',
  paid_on         DATE,
  -- A weak entity: an installment exists only within its loan, so the loan is
  -- part of its primary key (installment 1 of loan 7, installment 2, ...).
  CONSTRAINT loan_schedule_pk          PRIMARY KEY (loan_id, installment_no),
  CONSTRAINT loan_schedule_due_uk      UNIQUE (loan_id, due_date),
  CONSTRAINT loan_schedule_loan_fk     FOREIGN KEY (loan_id) REFERENCES loans (loan_id),
  CONSTRAINT loan_schedule_no_ck       CHECK (installment_no >= 1),
  CONSTRAINT loan_schedule_amount_ck   CHECK (principal_due + interest_due > 0),
  CONSTRAINT loan_schedule_paid_ck     CHECK (principal_paid <= principal_due AND interest_paid <= interest_due),
  CONSTRAINT loan_schedule_status_ck   CHECK (status IN ('DUE', 'PARTIAL', 'PAID', 'OVERDUE')),
  -- The status must agree with the amounts paid. OVERDUE (due date passed, not
  -- fully paid) is set by the nightly arrears job.
  CONSTRAINT loan_schedule_state_ck    CHECK (
    (status = 'PAID'    AND principal_paid = principal_due AND interest_paid = interest_due AND paid_on IS NOT NULL) OR
    (status = 'PARTIAL' AND principal_paid + interest_paid > 0
                        AND principal_paid + interest_paid < principal_due + interest_due AND paid_on IS NULL) OR
    (status = 'DUE'     AND principal_paid = 0 AND interest_paid = 0 AND paid_on IS NULL) OR
    (status = 'OVERDUE' AND principal_paid + interest_paid < principal_due + interest_due AND paid_on IS NULL))
);
-- The primary key index (loan_id, installment_no) also serves the foreign key on loan_id.
COMMENT ON TABLE  loan_schedule           IS 'Repayment schedule: one row per monthly installment, generated by pkg_loan at disbursement.';
COMMENT ON COLUMN loan_schedule.total_due IS 'Virtual column: principal_due + interest_due.';
--rollback DROP TABLE loan_schedule PURGE;

