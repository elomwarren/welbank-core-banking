-- At most one PENDING request of a type for the same target. The request type
-- decides which column holds the target, so COALESCE picks the right one.
CREATE UNIQUE INDEX approval_requests_pending_ux ON approval_requests (
  CASE WHEN status = 'PENDING' THEN request_type END,
  CASE WHEN status = 'PENDING' THEN COALESCE(account_id, customer_id, txn_id, application_id, card_id) END);
