-- =============================================================================
-- 0006_loans_cards_control.sql — loans, debit cards, the maker-checker queue
-- and the audit trail. Completes the Tier 1 schema.
--
-- Loans follow the life of a real loan:
--   application (captured by a loan officer, decided by a credit manager)
--   -> loan (disbursed into the customer's account; its LOAN account holds
--      what is still owed) -> schedule (one row per monthly installment)
--   -> repayments (which installments each repayment transaction paid).
-- Ghana specifics:
--   * pricing: Ghana Reference Rate (GRR, published monthly as the benchmark
--     for loan pricing) plus the bank's margin for the borrower's risk;
--   * classification: Bank of Ghana prudential classes CURRENT, OLEM (Other
--     Loans Especially Mentioned), SUBSTANDARD, DOUBTFUL, LOSS, by days past
--     due. The bands and provisioning rates are DATA (loan_classes), not code:
--     the Bank of Ghana has changed them before (OLEM provisioning went from
--     10 % to 5 % in 2020), and data changes without a release.
-- Cards never store the card number (PCI DSS): only a masked number and the
-- processor's token.
-- The audit trail is an IMMUTABLE table: nobody, not even a DBA, can change or
-- delete its rows for five years (the record-keeping period of the
-- Anti-Money Laundering Act, 2020, Act 1044, s.32).
-- =============================================================================

