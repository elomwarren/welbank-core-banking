  CONSTRAINT approval_requests_status_ck    CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
  -- Maker-checker: nobody decides their own request.
  CONSTRAINT approval_requests_checker_ck   CHECK (decided_by <> requested_by),
  CONSTRAINT approval_requests_decided_ck   CHECK (
    (status IN ('APPROVED', 'REJECTED') AND decided_by IS NOT NULL AND decided_at IS NOT NULL) OR
    (status IN ('PENDING', 'CANCELLED') AND decided_by IS NULL AND decided_at IS NULL)),
  CONSTRAINT approval_requests_rejected_ck  CHECK (status <> 'REJECTED' OR decision_note IS NOT NULL)
);
