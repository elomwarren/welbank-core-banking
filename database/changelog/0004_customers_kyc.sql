  CONSTRAINT customer_contacts_customer_fk FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
  CONSTRAINT customer_contacts_type_ck     CHECK (contact_type IN ('MOBILE', 'HOME', 'WORK', 'EMAIL')),
  -- An EMAIL row holds an e-mail only; every other type holds a phone number only.
  CONSTRAINT customer_contacts_value_ck    CHECK (
    (contact_type = 'EMAIL' AND email IS NOT NULL AND phone IS NULL) OR
    (contact_type <> 'EMAIL' AND phone IS NOT NULL AND email IS NULL))
);
CREATE INDEX customer_contacts_customer_ix ON customer_contacts (customer_id);
-- At most one primary phone and one primary e-mail per customer.
CREATE UNIQUE INDEX customer_contacts_primary_ux ON customer_contacts (
  CASE WHEN is_primary THEN customer_id END,
  CASE WHEN is_primary THEN CASE contact_type WHEN 'EMAIL' THEN 'EMAIL' ELSE 'PHONE' END END);
COMMENT ON TABLE  customer_contacts             IS 'Phone numbers and e-mail addresses (NIA secondary data).';
COMMENT ON COLUMN customer_contacts.is_verified IS 'Confirmed by a one-time code (simulated in this project).';
