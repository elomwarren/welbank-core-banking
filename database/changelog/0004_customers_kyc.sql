--changeset elomwarren:0004-identity-documents
CREATE TABLE identity_documents (
  document_id      NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  customer_id      NUMBER(10)    NOT NULL,
  doc_type         VARCHAR2(20)  NOT NULL,
  doc_number       VARCHAR2(30)  NOT NULL,
  issuing_country  iso_country_d NOT NULL,
  expiry_date      DATE,
  is_primary       BOOLEAN       DEFAULT ON NULL FALSE,
  created_at       TIMESTAMP     DEFAULT ON NULL SYSTIMESTAMP,
  created_by       VARCHAR2(128) DEFAULT ON NULL SYS_CONTEXT('USERENV', 'SESSION_USER'),
  CONSTRAINT identity_documents_pk          PRIMARY KEY (document_id),
  -- The same document can never belong to two customers.
  CONSTRAINT identity_documents_uk          UNIQUE (doc_type, doc_number, issuing_country),
  CONSTRAINT identity_documents_customer_fk FOREIGN KEY (customer_id)     REFERENCES customers (customer_id),
  CONSTRAINT identity_documents_country_fk  FOREIGN KEY (issuing_country) REFERENCES countries (country_code),
  CONSTRAINT identity_documents_type_ck     CHECK (doc_type IN ('GHANA_CARD', 'NON_CITIZEN_CARD', 'REFUGEE_CARD', 'PASSPORT', 'DIPLOMATIC_PASSPORT')),
  -- Cards issued by NIA are Ghanaian documents, and the Ghana Card PIN has a fixed format.
  CONSTRAINT identity_documents_nia_ck      CHECK (doc_type NOT IN ('GHANA_CARD', 'NON_CITIZEN_CARD', 'REFUGEE_CARD') OR issuing_country = 'GHA'),
  CONSTRAINT identity_documents_pin_ck      CHECK (doc_type <> 'GHANA_CARD' OR REGEXP_LIKE(doc_number, '^GHA-[0-9]{9}-[0-9]$'))
);
CREATE INDEX identity_documents_customer_ix ON identity_documents (customer_id);
CREATE INDEX identity_documents_country_ix  ON identity_documents (issuing_country);
-- At most ONE primary document per customer: a unique function-based index that
-- only holds rows where is_primary is TRUE (other rows give NULL, which unique
-- indexes ignore).
CREATE UNIQUE INDEX identity_documents_primary_ux ON identity_documents (CASE WHEN is_primary THEN customer_id END);
COMMENT ON TABLE  identity_documents          IS 'Identity documents a customer is known by. Never a copy or scan of the card itself (L.I. 2111, as amended in 2026).';
COMMENT ON COLUMN identity_documents.doc_type IS 'GHANA_CARD / NON_CITIZEN_CARD / REFUGEE_CARD (NIA cards, the rule); PASSPORT (Ghanaians abroad without access to the card); DIPLOMATIC_PASSPORT (diplomats, exempt under L.I. 2111).';
COMMENT ON COLUMN identity_documents.is_primary IS 'The document used for verification. At most one per customer (identity_documents_primary_ux).';
--rollback DROP TABLE identity_documents PURGE;

--changeset elomwarren:0004-identity-verifications
CREATE TABLE identity_verifications (
  verification_id  NUMBER(12)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  customer_id      NUMBER(10)    NOT NULL,
  document_id      NUMBER(10)    NOT NULL,
  purpose          VARCHAR2(16)  NOT NULL,
  method           VARCHAR2(16)  NOT NULL,
  result           VARCHAR2(8)   NOT NULL,
  nia_reference    VARCHAR2(40),
  error_code       VARCHAR2(20),
  is_simulated     BOOLEAN       DEFAULT ON NULL TRUE,
  performed_by     NUMBER(10)    NOT NULL,
  performed_at     TIMESTAMP     DEFAULT ON NULL SYSTIMESTAMP,
  CONSTRAINT identity_verifications_pk          PRIMARY KEY (verification_id),
  CONSTRAINT identity_verifications_customer_fk FOREIGN KEY (customer_id)  REFERENCES customers (customer_id),
  CONSTRAINT identity_verifications_document_fk FOREIGN KEY (document_id)  REFERENCES identity_documents (document_id),
  CONSTRAINT identity_verifications_officer_fk  FOREIGN KEY (performed_by) REFERENCES employees (employee_id),
  CONSTRAINT identity_verifications_purpose_ck  CHECK (purpose IN ('ONBOARDING', 'TRANSACTION', 'PERIODIC_REVIEW', 'THIRD_PARTY')),
  CONSTRAINT identity_verifications_method_ck   CHECK (method IN ('FACE', 'SINGLE_FINGER', 'NO_CARD_PRESENT', 'OFFLINE_DEVICE', 'LIVENESS', 'MANUAL_DOCUMENT')),
  CONSTRAINT identity_verifications_result_ck   CHECK (result IN ('MATCH', 'NO_MATCH', 'FAILED')),
  -- A MATCH carries NIA's reference; a FAILED attempt carries the system error code.
  CONSTRAINT identity_verifications_ref_ck      CHECK (result <> 'MATCH'  OR nia_reference IS NOT NULL),
  CONSTRAINT identity_verifications_error_ck    CHECK (result <> 'FAILED' OR error_code IS NOT NULL)
);
CREATE INDEX identity_verifications_customer_ix ON identity_verifications (customer_id, performed_at);
CREATE INDEX identity_verifications_document_ix ON identity_verifications (document_id);
CREATE INDEX identity_verifications_officer_ix  ON identity_verifications (performed_by);
COMMENT ON TABLE  identity_verifications              IS 'Every identity verification attempt, kept as required ("AIs shall keep records of the verification"). Append-only: rows are never updated or deleted (enforced by privileges).';
COMMENT ON COLUMN identity_verifications.method       IS 'FACE, SINGLE_FINGER, NO_CARD_PRESENT (10 fingers), OFFLINE_DEVICE (card on the handheld device), LIVENESS (digital channels), MANUAL_DOCUMENT (passport cases only).';
COMMENT ON COLUMN identity_verifications.result       IS 'MATCH, NO_MATCH (data does not match a registered person), FAILED (poor biometric quality or network).';
COMMENT ON COLUMN identity_verifications.nia_reference IS 'Reference returned by NIA (or the unique verification code it issues after an escalation).';
COMMENT ON COLUMN identity_verifications.is_simulated IS 'TRUE in this project: NIA is not reachable, so results are simulated.';
--rollback DROP TABLE identity_verifications PURGE;

