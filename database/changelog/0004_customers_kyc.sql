CREATE TABLE customer_contacts (
  contact_id     NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  customer_id    NUMBER(10)    NOT NULL,
  contact_type   VARCHAR2(10)  NOT NULL,
  phone          phone_d,
  email          email_d,
  is_primary     BOOLEAN       DEFAULT ON NULL FALSE,
  is_verified    BOOLEAN       DEFAULT ON NULL FALSE,
  created_at     TIMESTAMP     DEFAULT ON NULL SYSTIMESTAMP,
  created_by     VARCHAR2(128) DEFAULT ON NULL SYS_CONTEXT('USERENV', 'SESSION_USER'),
