CREATE TABLE customers (
  customer_id              NUMBER(10)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
  -- CAST: Oracle cannot know how long LPAD of a number may get, and refuses a
  -- default that might not fit (ORA-01401) unless its length is stated.
  customer_no              VARCHAR2(12)         DEFAULT ON NULL CAST('CUS' || LPAD(customer_no_seq.NEXTVAL, 8, '0') AS VARCHAR2(12)),
  -- Primary data: from NIA.
  title                    VARCHAR2(5),
  first_name               VARCHAR2(40)         NOT NULL,
  middle_name              VARCHAR2(40),
  last_name                VARCHAR2(40)         NOT NULL,
  previous_names           VARCHAR2(200),
  sex                      sex_d                NOT NULL,
  date_of_birth            DATE                 NOT NULL,
  place_of_birth           VARCHAR2(60),
  nationality              iso_country_d        NOT NULL,
  nia_last_synced_at       TIMESTAMP,
  -- Secondary data and relationship: maintained by the bank.
  country_of_residence     iso_country_d        DEFAULT ON NULL 'GHA',
  marital_status           VARCHAR2(10),
  home_branch_id           NUMBER(10)           NOT NULL,
  relationship_officer_id  NUMBER(10),
  employment_status        VARCHAR2(15)         NOT NULL,
  occupation               VARCHAR2(60),
  employer_name            VARCHAR2(100),
  income_band              VARCHAR2(12)         NOT NULL,
  source_of_funds          VARCHAR2(12)         NOT NULL,
  account_purpose          VARCHAR2(12)         NOT NULL,
  expected_monthly_volume  non_negative_money_d NOT NULL,
  -- Risk and due diligence.
  is_pep                   BOOLEAN              DEFAULT ON NULL FALSE,
  pep_details              VARCHAR2(400),
  sanctions_status         VARCHAR2(15)         DEFAULT ON NULL 'NOT_SCREENED',
  risk_rating              VARCHAR2(6),
  due_diligence_level      VARCHAR2(10)         DEFAULT ON NULL 'STANDARD',
  -- KYC lifecycle.
  kyc_status               VARCHAR2(20)         DEFAULT ON NULL 'PENDING_VERIFICATION',
  kyc_deferral_until       DATE,
  kyc_approved_by          NUMBER(10),
  kyc_approved_at          TIMESTAMP,
  next_kyc_review_on       DATE,
  status                   VARCHAR2(12)         DEFAULT ON NULL 'PENDING_KYC',
  -- Consent (Data Protection Act, 2012, Act 843).
  data_consent_at          TIMESTAMP            NOT NULL,
  marketing_consent        BOOLEAN              DEFAULT ON NULL FALSE,
  created_at               TIMESTAMP            DEFAULT ON NULL SYSTIMESTAMP,
  created_by               VARCHAR2(128)        DEFAULT ON NULL SYS_CONTEXT('USERENV', 'SESSION_USER'),
  updated_at               TIMESTAMP,
  updated_by               VARCHAR2(128),
  CONSTRAINT customers_pk                  PRIMARY KEY (customer_id),
  CONSTRAINT customers_no_uk               UNIQUE (customer_no),
  CONSTRAINT customers_nationality_fk      FOREIGN KEY (nationality)             REFERENCES countries (country_code),
  CONSTRAINT customers_residence_fk        FOREIGN KEY (country_of_residence)    REFERENCES countries (country_code),
  CONSTRAINT customers_branch_fk           FOREIGN KEY (home_branch_id)          REFERENCES branches (branch_id),
  CONSTRAINT customers_officer_fk          FOREIGN KEY (relationship_officer_id) REFERENCES employees (employee_id),
  CONSTRAINT customers_kyc_approver_fk     FOREIGN KEY (kyc_approved_by)         REFERENCES employees (employee_id),
  CONSTRAINT customers_title_ck            CHECK (title IN ('MR', 'MRS', 'MS', 'MISS', 'DR', 'PROF', 'REV', 'HON', 'NANA')),
  CONSTRAINT customers_marital_ck          CHECK (marital_status IN ('SINGLE', 'MARRIED', 'DIVORCED', 'WIDOWED', 'SEPARATED')),
  CONSTRAINT customers_employment_ck       CHECK (employment_status IN ('EMPLOYED', 'SELF_EMPLOYED', 'STUDENT', 'RETIRED', 'UNEMPLOYED')),
  CONSTRAINT customers_income_ck           CHECK (income_band IN ('UNDER_1K', '1K_5K', '5K_10K', '10K_50K', 'OVER_50K')),
  CONSTRAINT customers_funds_ck            CHECK (source_of_funds IN ('SALARY', 'BUSINESS', 'SAVINGS', 'PENSION', 'REMITTANCE', 'INVESTMENT', 'GIFT', 'OTHER')),
  CONSTRAINT customers_purpose_ck          CHECK (account_purpose IN ('SAVINGS', 'SALARY', 'BUSINESS', 'INVESTMENT', 'REMITTANCE', 'OTHER')),
  CONSTRAINT customers_pep_ck              CHECK (is_pep = FALSE OR pep_details IS NOT NULL),
  CONSTRAINT customers_sanctions_ck        CHECK (sanctions_status IN ('NOT_SCREENED', 'CLEAR', 'POTENTIAL_MATCH', 'CONFIRMED_MATCH')),
  CONSTRAINT customers_risk_ck             CHECK (risk_rating IN ('LOW', 'MEDIUM', 'HIGH')),
  CONSTRAINT customers_cdd_ck              CHECK (due_diligence_level IN ('SIMPLIFIED', 'STANDARD', 'ENHANCED')),
  -- A politically exposed person always gets enhanced due diligence.
  CONSTRAINT customers_pep_edd_ck          CHECK (is_pep = FALSE OR due_diligence_level = 'ENHANCED'),
  CONSTRAINT customers_kyc_status_ck       CHECK (kyc_status IN ('PENDING_VERIFICATION', 'VERIFIED', 'DEFERRED', 'REJECTED', 'REVIEW_DUE')),
  -- A deferral (failed onboarding verification) always has its 90-day end date.
  CONSTRAINT customers_deferral_ck         CHECK (
    (kyc_status = 'DEFERRED' AND kyc_deferral_until IS NOT NULL) OR
    (kyc_status <> 'DEFERRED' AND kyc_deferral_until IS NULL)),
  -- Verified KYC records who approved it, when, and the resulting risk rating.
  CONSTRAINT customers_kyc_approved_ck     CHECK (
    kyc_status <> 'VERIFIED' OR
    (kyc_approved_by IS NOT NULL AND kyc_approved_at IS NOT NULL AND risk_rating IS NOT NULL)),
  CONSTRAINT customers_status_ck           CHECK (status IN ('PENDING_KYC', 'ACTIVE', 'DORMANT', 'CLOSED', 'BLOCKED'))
);
CREATE INDEX customers_nationality_ix   ON customers (nationality);
CREATE INDEX customers_residence_ix     ON customers (country_of_residence);
CREATE INDEX customers_branch_ix        ON customers (home_branch_id);
CREATE INDEX customers_officer_ix       ON customers (relationship_officer_id);
CREATE INDEX customers_kyc_approver_ix  ON customers (kyc_approved_by);
-- Function-based index: staff search by name, whatever the capitalisation.
CREATE INDEX customers_name_ix          ON customers (UPPER(last_name), UPPER(first_name));
COMMENT ON TABLE  customers                     IS 'Individual customers. Identity (primary) data comes from NIA; the rest is maintained by the bank.';
COMMENT ON COLUMN customers.customer_no         IS 'Business number shown to people, from customer_no_seq. customer_id stays internal.';
COMMENT ON COLUMN customers.previous_names      IS 'NIA primary data. Changed only through NIA, never typed by staff.';
COMMENT ON COLUMN customers.nia_last_synced_at  IS 'When primary data was last refreshed from an NIA verification.';
COMMENT ON COLUMN customers.expected_monthly_volume IS 'Declared monthly activity (GHS); real activity far above it is flagged for review.';
COMMENT ON COLUMN customers.is_pep              IS 'Politically exposed person: requires enhanced due diligence.';
COMMENT ON COLUMN customers.kyc_status          IS 'PENDING_VERIFICATION, VERIFIED, DEFERRED (failed NIA check: 90 days to fix, deposits only), REJECTED, REVIEW_DUE.';
COMMENT ON COLUMN customers.data_consent_at     IS 'When the customer consented to processing of personal data (Act 843). Required.';
--rollback DROP TABLE customers PURGE;

