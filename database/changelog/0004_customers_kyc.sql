CREATE TABLE customer_addresses (
  address_id       NUMBER(10)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
  customer_id      NUMBER(10)           NOT NULL,
  address_type     VARCHAR2(12)         NOT NULL,
  address_line     VARCHAR2(150)        NOT NULL,
  town             VARCHAR2(60)         NOT NULL,
  region_id        NUMBER(10),
  country_code     iso_country_d        DEFAULT ON NULL 'GHA',
  digital_address  gh_digital_address_d,
  landmark         VARCHAR2(200),
  resident_since   DATE,
  proof_type       VARCHAR2(20),
  proof_date       DATE,
  is_current       BOOLEAN              DEFAULT ON NULL TRUE,
  created_at       TIMESTAMP            DEFAULT ON NULL SYSTIMESTAMP,
  created_by       VARCHAR2(128)        DEFAULT ON NULL SYS_CONTEXT('USERENV', 'SESSION_USER'),
  CONSTRAINT customer_addresses_pk          PRIMARY KEY (address_id),
  CONSTRAINT customer_addresses_customer_fk FOREIGN KEY (customer_id)  REFERENCES customers (customer_id),
  CONSTRAINT customer_addresses_region_fk   FOREIGN KEY (region_id)    REFERENCES regions (region_id),
  CONSTRAINT customer_addresses_country_fk  FOREIGN KEY (country_code) REFERENCES countries (country_code),
  CONSTRAINT customer_addresses_type_ck     CHECK (address_type IN ('RESIDENTIAL', 'POSTAL', 'WORK')),
  -- An address in Ghana is in a region; a residential address in Ghana has a GhanaPost digital address.
  CONSTRAINT customer_addresses_region_ck   CHECK (country_code <> 'GHA' OR region_id IS NOT NULL),
  CONSTRAINT customer_addresses_gps_ck      CHECK (address_type <> 'RESIDENTIAL' OR country_code <> 'GHA' OR digital_address IS NOT NULL),
  CONSTRAINT customer_addresses_proof_ck    CHECK (proof_type IN ('UTILITY_BILL', 'TENANCY_AGREEMENT', 'EMPLOYER_LETTER', 'LANDLORD_LETTER', 'BANK_STATEMENT')),
  CONSTRAINT customer_addresses_proofdt_ck  CHECK (proof_type IS NULL OR proof_date IS NOT NULL)
);
CREATE INDEX customer_addresses_customer_ix ON customer_addresses (customer_id);
CREATE INDEX customer_addresses_region_ix   ON customer_addresses (region_id);
CREATE INDEX customer_addresses_country_ix  ON customer_addresses (country_code);
-- One CURRENT address of each type per customer (old ones are kept as history).
CREATE UNIQUE INDEX customer_addresses_current_ux ON customer_addresses (
  CASE WHEN is_current THEN customer_id END,
  CASE WHEN is_current THEN address_type END);
COMMENT ON TABLE  customer_addresses             IS 'Customer addresses (NIA secondary data, maintained by the bank). Changes add a new row; the old one gets is_current = FALSE.';
COMMENT ON COLUMN customer_addresses.landmark    IS 'Directions people actually use, e.g. "behind the Methodist church".';
COMMENT ON COLUMN customer_addresses.proof_type  IS 'Document seen as proof of this address; its image, if kept, is in customer_files (PROOF_OF_ADDRESS).';
