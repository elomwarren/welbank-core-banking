-- =============================================================================
-- 0004_customers_kyc.sql — customers and Know-Your-Customer (KYC) data.
--
-- Follows the Bank of Ghana Supervisory Guidance Note on the use of the Ghana
-- Card (November 2025, Notice BG/GOV/SEC/2025/36) and L.I. 2111:
--   * customers are identified ONLY by the Ghana Card, Non-Citizen Identity
--     Card or Refugee Identity Card, verified biometrically through NIA
--     (exceptions: passport for Ghanaians abroad without access to the card,
--     diplomatic passport for diplomats);
--   * PRIMARY data (names, previous names, date of birth, sex, nationality,
--     picture) comes from NIA and is changed only by re-verifying; SECONDARY
--     data (phones, addresses, next of kin, occupation, e-mail) is maintained
--     by the bank;
--   * every verification is recorded (identity_verifications, append-only);
--   * a failed onboarding verification leaves the customer in a 90-day
--     deferral, during which accounts accept deposits but no debits;
--   * the Ghana Card is NEVER photocopied or scanned: since the 2026 amendment
--     of L.I. 2111 that is a criminal offence, so no table holds card images.
-- NIA is not reachable from this project, so verifications are simulated and
-- marked as such (is_simulated).
-- =============================================================================

