CREATE TABLE customer_files (
  file_id      NUMBER(12)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  customer_id  NUMBER(10)    NOT NULL,
  file_kind    VARCHAR2(20)  NOT NULL,
  mime_type    VARCHAR2(12)  NOT NULL,
  byte_size    NUMBER(8)     NOT NULL,
  sha256       VARCHAR2(64)  NOT NULL,
  content      BLOB          NOT NULL,
  is_current   BOOLEAN       DEFAULT ON NULL TRUE,
  captured_by  NUMBER(10)    NOT NULL,
  captured_at  TIMESTAMP     DEFAULT ON NULL SYSTIMESTAMP,
  CONSTRAINT customer_files_pk          PRIMARY KEY (file_id),
  CONSTRAINT customer_files_customer_fk FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
  CONSTRAINT customer_files_officer_fk  FOREIGN KEY (captured_by) REFERENCES employees (employee_id),
  -- No ID card images: photocopying the Ghana Card is an offence (L.I. 2111, as amended in 2026).
  CONSTRAINT customer_files_kind_ck     CHECK (file_kind IN ('PHOTO', 'SIGNATURE', 'PROOF_OF_ADDRESS')),
  CONSTRAINT customer_files_mime_ck     CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp')),
  CONSTRAINT customer_files_size_ck     CHECK (byte_size BETWEEN 1 AND 2097152),
  CONSTRAINT customer_files_sha256_ck   CHECK (REGEXP_LIKE(sha256, '^[0-9a-f]{64}$'))
)
-- The picture bytes live in their own encrypted tablespace, as SecureFiles.
LOB (content) STORE AS SECUREFILE customer_files_content_lob (TABLESPACE welbank_docs);
CREATE INDEX customer_files_customer_ix ON customer_files (customer_id);
CREATE INDEX customer_files_officer_ix  ON customer_files (captured_by);
-- One CURRENT file of each kind per customer (replaced ones stay as history).
CREATE UNIQUE INDEX customer_files_current_ux ON customer_files (
  CASE WHEN is_current THEN customer_id END,
  CASE WHEN is_current THEN file_kind END);
COMMENT ON TABLE  customer_files           IS 'Customer photo (taken live), specimen signature and proof-of-address images. Never images of the ID card.';
COMMENT ON COLUMN customer_files.content   IS 'The image bytes (SecureFile LOB in tablespace WELBANK_DOCS, encrypted by TDE).';
COMMENT ON COLUMN customer_files.byte_size IS 'Size in bytes, at most 2 MB. Must equal DBMS_LOB.GETLENGTH(content) (checked by pkg_kyc; a CHECK constraint cannot read a LOB).';
COMMENT ON COLUMN customer_files.sha256    IS 'SHA-256 of the bytes in lower-case hex: detects tampering and duplicates.';
--rollback DROP TABLE customer_files PURGE;
