--changeset elomwarren:0003-countries
CREATE TABLE countries (
  country_code      iso_country_d NOT NULL,
  country_name      VARCHAR2(60)  NOT NULL,
  nationality_name  VARCHAR2(60)  NOT NULL,
  is_ecowas         BOOLEAN       DEFAULT ON NULL FALSE,
  risk_level        VARCHAR2(6)   DEFAULT ON NULL 'LOW',
  created_at        TIMESTAMP     DEFAULT ON NULL SYSTIMESTAMP,
  created_by        VARCHAR2(128) DEFAULT ON NULL SYS_CONTEXT('USERENV', 'SESSION_USER'),
  CONSTRAINT countries_pk          PRIMARY KEY (country_code),
  CONSTRAINT countries_name_uk     UNIQUE (country_name),
  CONSTRAINT countries_risk_ck     CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH'))
);
COMMENT ON TABLE  countries                  IS 'Countries, for nationality, residence and ID issuing country. Keyed by ISO 3166-1 alpha-3 code.';
COMMENT ON COLUMN countries.nationality_name IS 'What a citizen is called, e.g. Ghanaian, Nigerian. Shown in nationality drop-downs.';
COMMENT ON COLUMN countries.is_ecowas        IS 'Member of ECOWAS. ECOWAS nationals resident in Ghana are onboarded with the Non-Citizen Identity Card.';
COMMENT ON COLUMN countries.risk_level       IS 'Bank policy input to customer risk rating (not an official list).';
--rollback DROP TABLE countries PURGE;

--changeset elomwarren:0003-employees
CREATE TABLE employees (
  employee_id          NUMBER(10)       GENERATED BY DEFAULT ON NULL AS IDENTITY,
  first_name           VARCHAR2(40)     NOT NULL,
  middle_name          VARCHAR2(40),
  last_name            VARCHAR2(40)     NOT NULL,
  sex                  sex_d            NOT NULL,
  date_of_birth        DATE             NOT NULL,
  nationality          iso_country_d    NOT NULL,
  work_email           email_d          NOT NULL,
  phone                phone_d          NOT NULL,
  residential_address  VARCHAR2(150),
  job_id               NUMBER(10)       NOT NULL,
  branch_id            NUMBER(10)       NOT NULL,
  manager_id           NUMBER(10),
  salary               positive_money_d NOT NULL,
  hire_date            DATE             NOT NULL,
  termination_date     DATE,
  status               VARCHAR2(12)     DEFAULT ON NULL 'ACTIVE',
  db_username          VARCHAR2(128),
  created_at           TIMESTAMP        DEFAULT ON NULL SYSTIMESTAMP,
  created_by           VARCHAR2(128)    DEFAULT ON NULL SYS_CONTEXT('USERENV', 'SESSION_USER'),
  updated_at           TIMESTAMP,
  updated_by           VARCHAR2(128),
  CONSTRAINT employees_pk              PRIMARY KEY (employee_id),
  CONSTRAINT employees_work_email_uk   UNIQUE (work_email),
  CONSTRAINT employees_db_username_uk  UNIQUE (db_username),
  CONSTRAINT employees_nationality_fk  FOREIGN KEY (nationality) REFERENCES countries (country_code),
  CONSTRAINT employees_job_fk          FOREIGN KEY (job_id)      REFERENCES jobs (job_id),
  CONSTRAINT employees_branch_fk       FOREIGN KEY (branch_id)   REFERENCES branches (branch_id),
  CONSTRAINT employees_manager_fk      FOREIGN KEY (manager_id)  REFERENCES employees (employee_id),
  CONSTRAINT employees_status_ck       CHECK (status IN ('ACTIVE', 'ON_LEAVE', 'SUSPENDED', 'TERMINATED')),
  CONSTRAINT employees_dates_ck        CHECK (termination_date IS NULL OR termination_date >= hire_date),
  -- A terminated employee has a termination date, and only a terminated one does.
  CONSTRAINT employees_terminated_ck   CHECK (
    (status = 'TERMINATED' AND termination_date IS NOT NULL) OR
    (status <> 'TERMINATED' AND termination_date IS NULL)),
  CONSTRAINT employees_not_own_mgr_ck  CHECK (manager_id IS NULL OR manager_id <> employee_id),
  CONSTRAINT employees_db_username_ck  CHECK (db_username = UPPER(db_username))
);
CREATE INDEX employees_nationality_ix ON employees (nationality);
CREATE INDEX employees_job_ix         ON employees (job_id);
CREATE INDEX employees_branch_ix      ON employees (branch_id);
CREATE INDEX employees_manager_ix     ON employees (manager_id);
COMMENT ON TABLE  employees             IS 'Bank staff. The department comes from the job (jobs.department_id), not stored again here.';
COMMENT ON COLUMN employees.manager_id  IS 'Line manager; used for approvals (maker-checker).';
COMMENT ON COLUMN employees.salary      IS 'Yearly salary in GHS. Must sit within the job''s range (checked by pkg_staff, a cross-table rule).';
COMMENT ON COLUMN employees.db_username IS 'The employee''s own Oracle user, upper case. NULL = no system access. The web app proxies as this user.';
--rollback DROP TABLE employees PURGE;

--changeset elomwarren:0003-employees-updated-trg endDelimiter:/
CREATE OR REPLACE TRIGGER employees_updated_trg
  BEFORE UPDATE ON employees
  FOR EACH ROW
BEGIN
  -- Who changed the row and when. With proxy authentication SESSION_USER is the
  -- employee using the web app, not the application account.
  :NEW.updated_at := SYSTIMESTAMP;
  :NEW.updated_by := SYS_CONTEXT('USERENV', 'SESSION_USER');
END;
/
--rollback DROP TRIGGER employees_updated_trg
