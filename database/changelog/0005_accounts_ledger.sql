CREATE TABLE accounts (
  account_id         NUMBER(12)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
  account_no         VARCHAR2(13)         DEFAULT ON NULL CAST('10' || LPAD(account_no_seq.NEXTVAL, 11, '0') AS VARCHAR2(13)),
  account_class      VARCHAR2(8)          NOT NULL,
  internal_purpose   VARCHAR2(16),
  product_id         NUMBER(10),
  branch_id          NUMBER(10)           NOT NULL,
  currency_code      iso_currency_d       NOT NULL,
  account_name       VARCHAR2(100)        NOT NULL,
  mandate            VARCHAR2(14),
  status             VARCHAR2(16)         DEFAULT ON NULL 'PENDING_APPROVAL',
  post_no_debit      BOOLEAN              DEFAULT ON NULL TRUE,
  -- Virtual column: computed from the row on every read, never stored. Which
  -- kind of line makes the balance grow: a credit for money the bank owes
  -- (customer deposits, income, capital), a debit for what it owns or is owed
  -- (vault cash, loans, expenses).
  normal_side        VARCHAR2(6)          GENERATED ALWAYS AS (
                       CASE
                         WHEN account_class = 'CUSTOMER' THEN 'CREDIT'
                         WHEN account_class = 'LOAN'     THEN 'DEBIT'
                         WHEN internal_purpose IN ('FEE_INCOME', 'INTEREST_INCOME', 'CAPITAL') THEN 'CREDIT'
                         ELSE 'DEBIT'
                       END) VIRTUAL,
  ledger_balance     money_d              DEFAULT ON NULL 0,
  available_balance  money_d              DEFAULT ON NULL 0,
  overdraft_limit    non_negative_money_d DEFAULT ON NULL 0,
  opened_on          DATE                 DEFAULT ON NULL TRUNC(SYSDATE),
  closed_on          DATE,
  opened_by          NUMBER(10),
  checked_by         NUMBER(10),
  checked_at         TIMESTAMP,
  last_activity_at   TIMESTAMP,
  created_at         TIMESTAMP            DEFAULT ON NULL SYSTIMESTAMP,
  created_by         VARCHAR2(128)        DEFAULT ON NULL SYS_CONTEXT('USERENV', 'SESSION_USER'),
  updated_at         TIMESTAMP,
  updated_by         VARCHAR2(128),
  CONSTRAINT accounts_pk              PRIMARY KEY (account_id),
  CONSTRAINT accounts_no_uk           UNIQUE (account_no),
  -- Composite foreign key: the pair (product, currency) must exist in
  -- account_products, so the account is in its product's currency. A foreign
  -- key with a NULL column is not checked, so INTERNAL and LOAN accounts
  -- (no product) are not affected.
  CONSTRAINT accounts_product_fk      FOREIGN KEY (product_id, currency_code) REFERENCES account_products (product_id, currency_code),
  CONSTRAINT accounts_branch_fk       FOREIGN KEY (branch_id)     REFERENCES branches (branch_id),
  CONSTRAINT accounts_currency_fk     FOREIGN KEY (currency_code) REFERENCES currencies (currency_code),
  CONSTRAINT accounts_opened_by_fk    FOREIGN KEY (opened_by)     REFERENCES employees (employee_id),
  CONSTRAINT accounts_checked_by_fk   FOREIGN KEY (checked_by)    REFERENCES employees (employee_id),
  CONSTRAINT accounts_no_ck           CHECK (REGEXP_LIKE(account_no, '^[0-9]{13}$')),
  CONSTRAINT accounts_class_ck        CHECK (account_class IN ('CUSTOMER', 'LOAN', 'INTERNAL')),
  -- Only the bank's internal accounts have a purpose, and they always have one.
  -- "IS NOT NULL" is needed: for a NULL purpose, "IN (...)" is UNKNOWN, and a
  -- CHECK constraint only rejects FALSE (same trap as account_products_term_ck).
  CONSTRAINT accounts_purpose_ck      CHECK (
    (account_class = 'INTERNAL' AND internal_purpose IS NOT NULL
      AND internal_purpose IN ('VAULT_CASH', 'FEE_INCOME', 'INTEREST_INCOME', 'INTEREST_EXPENSE', 'CAPITAL', 'SUSPENSE')) OR
    (account_class <> 'INTERNAL' AND internal_purpose IS NULL)),
  -- Customer accounts are sold as a product; loan accounts get theirs from the
  -- loans table (later changelog); internal accounts have none.
  CONSTRAINT accounts_product_ck      CHECK (
    (account_class = 'CUSTOMER' AND product_id IS NOT NULL) OR
    (account_class <> 'CUSTOMER' AND product_id IS NULL)),
  -- Who may sign: customer and loan accounts have a mandate, internal ones do not.
  CONSTRAINT accounts_mandate_ck      CHECK (
    (account_class = 'INTERNAL' AND mandate IS NULL) OR
    (account_class <> 'INTERNAL' AND mandate IS NOT NULL AND mandate IN ('SOLE', 'EITHER_TO_SIGN', 'ALL_TO_SIGN'))),
  CONSTRAINT accounts_status_ck       CHECK (status IN ('PENDING_APPROVAL', 'ACTIVE', 'FROZEN', 'DORMANT', 'CLOSED', 'REJECTED')),
  -- Debits are possible only on an ACTIVE account. Freezing an account, or
  -- letting it go dormant, therefore also sets post_no_debit.
  CONSTRAINT accounts_debit_status_ck CHECK (post_no_debit = TRUE OR status = 'ACTIVE'),
  CONSTRAINT accounts_overdraft_ck    CHECK (overdraft_limit = 0 OR account_class = 'CUSTOMER'),
  -- Balances are kept on the account's normal side (positive = normal). A
  -- customer may go below zero only within the overdraft limit, a loan never
  -- (its limit is 0), and a vault cannot hold less than no cash.
  CONSTRAINT accounts_balance_ck      CHECK (
    (account_class IN ('CUSTOMER', 'LOAN') AND ledger_balance >= -overdraft_limit) OR
    (account_class = 'INTERNAL' AND (internal_purpose <> 'VAULT_CASH' OR ledger_balance >= 0))),
  -- Available = ledger balance minus amounts on hold, so never more than the ledger balance.
  CONSTRAINT accounts_available_ck    CHECK (available_balance <= ledger_balance),
  -- Maker-checker: a person opens the account (maker), another approves it (checker).
  CONSTRAINT accounts_opener_ck       CHECK (account_class = 'INTERNAL' OR opened_by IS NOT NULL),
  -- When either side is NULL the comparison is UNKNOWN, which a CHECK accepts.
  CONSTRAINT accounts_checker_ck      CHECK (checked_by <> opened_by),
  CONSTRAINT accounts_checked_pair_ck CHECK (
    (checked_by IS NULL AND checked_at IS NULL) OR
    (checked_by IS NOT NULL AND checked_at IS NOT NULL)),
  -- An account in use has been approved (internal accounts are set up by scripts).
  CONSTRAINT accounts_approved_ck     CHECK (
    account_class = 'INTERNAL' OR status IN ('PENDING_APPROVAL', 'REJECTED') OR checked_by IS NOT NULL),
  -- A closed account has a closing date and nothing left in it.
  CONSTRAINT accounts_closed_ck       CHECK (
    (status = 'CLOSED' AND closed_on IS NOT NULL AND ledger_balance = 0 AND available_balance = 0) OR
    (status <> 'CLOSED' AND closed_on IS NULL)),
  CONSTRAINT accounts_closed_date_ck  CHECK (closed_on >= opened_on)
);
