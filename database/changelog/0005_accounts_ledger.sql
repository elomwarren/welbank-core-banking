-- =============================================================================
-- 0005_accounts_ledger.sql — accounts, account holders, transactions and the
-- double-entry ledger.
--
-- How money is recorded (double-entry book-keeping):
--   * every money movement is ONE row in transactions (the business event:
--     "cash deposit of GHS 500 at Accra Central") and TWO OR MORE rows in
--     ledger_entries (its debit and credit lines);
--   * the debit lines and the credit lines of a transaction add up to the same
--     amount, so money is never created or lost;
--   * the bank's own money (vault cash, fee income, ...) lives in INTERNAL
--     accounts, so a cash deposit is: debit the branch vault, credit the customer.
-- Balances on accounts are changed only by pkg_posting (a later changelog),
-- which writes the lines and the new balances in the same transaction.
--
-- Rules the database enforces itself, whatever program writes the data:
--   * CHECK constraints for rules on one row (maker-checker, overdraft, ...);
--   * a composite foreign key for "an account is in its product's currency";
--   * SQL assertions (Oracle AI Database 23.26.1 and later) for rules across
--     rows and tables ("every customer account has a primary holder", "debits
--     need verified KYC", ...). Assertions cannot add rows up (no SUM), so
--   * "debits = credits" uses the classic ON COMMIT materialized view with a
--     CHECK constraint, verified when the transaction commits.
-- =============================================================================

