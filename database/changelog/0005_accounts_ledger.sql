-- -----------------------------------------------------------------------------
-- Debits = credits, checked at COMMIT.
-- An assertion cannot use SUM, so this uses the classic Oracle technique: a
-- materialized view keeps the net total of every transaction (debits minus
-- credits) and is refreshed by each COMMIT that changed ledger_entries; a
-- CHECK constraint on the view demands that every total is 0. An unbalanced
-- transaction makes the refresh fail, and the COMMIT fails with it
-- (ORA-12008 + ORA-02290), rolling the whole transaction back.
-- Trade-off: the refresh runs inside each such COMMIT, and refreshes of one
-- view take turns, so commits that post money queue for a moment. Fine at a
-- branch's pace; a very busy bank would rely on pkg_posting plus end-of-day
-- reconciliation instead (drop the view; nothing else depends on it).
-- -----------------------------------------------------------------------------

--changeset elomwarren:0005-ledger-entries-mv-log
--comment: Change log that lets the totals view be refreshed incrementally (FAST) instead of recomputed.
CREATE MATERIALIZED VIEW LOG ON ledger_entries
  WITH ROWID, SEQUENCE (txn_id, direction, amount) INCLUDING NEW VALUES;
--rollback DROP MATERIALIZED VIEW LOG ON ledger_entries;

--changeset elomwarren:0005-ledger-txn-totals-mv
-- COUNT(*) and COUNT(<the summed expression>) are not used by the rule; Oracle
-- needs them to fast-refresh a SUM after deletes.
CREATE MATERIALIZED VIEW ledger_txn_totals_mv
  REFRESH FAST ON COMMIT
AS
SELECT txn_id,
       SUM(CASE direction WHEN 'DR' THEN amount ELSE -amount END)   AS net_amount,
       COUNT(CASE direction WHEN 'DR' THEN amount ELSE -amount END) AS net_amount_count,
       COUNT(*)                                                     AS line_count
  FROM ledger_entries
 GROUP BY txn_id;
ALTER TABLE ledger_txn_totals_mv ADD CONSTRAINT ledger_txn_balanced_ck CHECK (net_amount = 0);
COMMENT ON MATERIALIZED VIEW ledger_txn_totals_mv IS 'Debits minus credits per transaction, refreshed at every COMMIT. ledger_txn_balanced_ck demands 0: unbalanced transactions cannot commit.';
--rollback DROP MATERIALIZED VIEW ledger_txn_totals_mv;

-- -----------------------------------------------------------------------------
-- SQL assertions: rules across rows and tables.
-- Oracle checks an assertion after each statement, or at COMMIT when it is
-- DEFERRABLE INITIALLY DEFERRED (for rules that need several statements to
-- satisfy, e.g. insert an account, then its holder). A violation raises
-- ORA-08601 naming the assertion; at COMMIT, ORA-02091 rolls back the whole
-- transaction.
-- Restrictions learned while writing these (Oracle validates each one
-- incrementally, "FAST", and refuses definitions it cannot validate that way):
--   * no SUM, COUNT, GROUP BY, outer joins or ANSI JOIN syntax;
--   * columns joined with "=" must be NOT NULL (or filtered with IS NOT NULL)
--     and of identical data types (ORA-08673);
--   * one rule per assertion: complex definitions must be split (ORA-08680).
-- Behaviour found in 23.26.3 (it contradicts the documentation): SET
-- CONSTRAINTS ALL DEFERRED also defers the NOT DEFERRABLE assertions until
-- COMMIT. They still hold at COMMIT, but programs (pkg_posting, tests) must
-- name the assertions they defer, never use ALL DEFERRED.
-- -----------------------------------------------------------------------------

--changeset elomwarren:0005-accounts-primary-holder-as
--comment: Every customer and loan account has a primary holder.
CREATE ASSERTION accounts_primary_holder_as CHECK (
  ALL (SELECT a.account_id FROM accounts a WHERE a.account_class IN ('CUSTOMER', 'LOAN')) a
  SATISFY (EXISTS (SELECT 1 FROM account_holders h
                    WHERE h.account_id = a.account_id AND h.holder_role = 'PRIMARY'))
) DEFERRABLE INITIALLY DEFERRED;
--rollback DROP ASSERTION accounts_primary_holder_as;

