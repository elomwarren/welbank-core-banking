COMMENT ON COLUMN accounts.account_no        IS 'Business number shown to people (13 digits), from account_no_seq. account_id stays internal.';
COMMENT ON COLUMN accounts.internal_purpose  IS 'INTERNAL accounts only: VAULT_CASH, FEE_INCOME, INTEREST_INCOME, INTEREST_EXPENSE, CAPITAL, SUSPENSE.';
COMMENT ON COLUMN accounts.mandate           IS 'Who signs: SOLE (the primary holder), EITHER_TO_SIGN or ALL_TO_SIGN (joint accounts).';
COMMENT ON COLUMN accounts.post_no_debit     IS 'TRUE = deposits only. Set until the account is approved, and while any holder''s KYC is not VERIFIED (BoG Ghana Card note, s.23.3).';
COMMENT ON COLUMN accounts.normal_side       IS 'Virtual column: CREDIT or DEBIT, the side that increases the balance.';
COMMENT ON COLUMN accounts.ledger_balance    IS 'Balance of all posted lines, on the normal side. Changed only by pkg_posting.';
COMMENT ON COLUMN accounts.available_balance IS 'Ledger balance minus holds (uncleared items, liens): what can be withdrawn.';
