               WHERE t.txn_id = e.txn_id AND t.status NOT IN ('POSTED', 'REVERSED')));
--rollback DROP ASSERTION ledger_entries_posted_as;

--changeset elomwarren:0005-transactions-lines-as
--comment: Every posted (or reversed) transaction has ledger lines.
CREATE ASSERTION transactions_lines_as CHECK (
  ALL (SELECT t.txn_id FROM transactions t WHERE t.status IN ('POSTED', 'REVERSED')) t
  SATISFY (EXISTS (SELECT 1 FROM ledger_entries e WHERE e.txn_id = t.txn_id))
) DEFERRABLE INITIALLY DEFERRED;
--rollback DROP ASSERTION transactions_lines_as;

--changeset elomwarren:0005-transactions-reversal-as
--comment: A REVERSED transaction has a posted REVERSAL pointing at it.
CREATE ASSERTION transactions_reversal_as CHECK (
  ALL (SELECT o.txn_id FROM transactions o WHERE o.status = 'REVERSED') o
  SATISFY (EXISTS (SELECT 1 FROM transactions r
                    WHERE r.reverses_txn_id IS NOT NULL AND r.reverses_txn_id = o.txn_id
                      AND r.status = 'POSTED'))
) DEFERRABLE INITIALLY DEFERRED;
--rollback DROP ASSERTION transactions_reversal_as;
